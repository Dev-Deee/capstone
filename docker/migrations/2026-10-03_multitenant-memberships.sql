-- Stage 1 multi-tenant foundation: institutions as tenants, users belong to
-- them through memberships.
--
-- Run BEFORE starting the new backend on every existing database:
--   docker exec -i cadence_db psql -U postgres -d cadence_db < docker/migrations/2026-10-03_multitenant-memberships.sql
-- Safe to re-run. Nothing is dropped: app_user.institution_id and user_roles are
-- left in place (no longer read by the app) so this can be rolled back; drop
-- them in a later migration once Stage 1 has settled.

BEGIN;

-- ── Institution: slug (immutable, unique) + status ───────────────────────
ALTER TABLE institution ADD COLUMN IF NOT EXISTS slug varchar(50);
ALTER TABLE institution ADD COLUMN IF NOT EXISTS status varchar(20) DEFAULT 'ACTIVE';

-- Slug from the name: lowercase, non-alphanumerics → '-', trimmed; ensure uniqueness with the id.
UPDATE institution
SET slug = trim(both '-' from regexp_replace(lower(name), '[^a-z0-9]+', '-', 'g'))
WHERE slug IS NULL;
UPDATE institution i
SET slug = i.slug || '-' || i.id
WHERE (SELECT count(*) FROM institution j WHERE j.slug = i.slug) > 1
   OR length(i.slug) < 3;
UPDATE institution SET status = 'ACTIVE' WHERE status IS NULL;

ALTER TABLE institution ALTER COLUMN slug SET NOT NULL;
ALTER TABLE institution ALTER COLUMN status SET NOT NULL;
DO $$ BEGIN
    ALTER TABLE institution ADD CONSTRAINT institution_slug_key UNIQUE (slug);
EXCEPTION WHEN duplicate_object OR duplicate_table THEN NULL; END $$;
ALTER TABLE institution DROP CONSTRAINT IF EXISTS institution_status_check;
ALTER TABLE institution ADD CONSTRAINT institution_status_check CHECK (status IN ('ACTIVE', 'PENDING', 'SUSPENDED'));

-- ── User: platform-admin flag, last institution used ─────────────────────
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS is_platform_admin boolean NOT NULL DEFAULT false;
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS last_active_institution_id bigint REFERENCES institution(id);
-- No longer mapped: a user's institutions now come from membership.
ALTER TABLE app_user ALTER COLUMN institution_id DROP NOT NULL;

-- ── Membership ───────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS membership (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     timestamp(6) NOT NULL,
    public_id      uuid NOT NULL UNIQUE,
    user_id        bigint NOT NULL REFERENCES app_user(id),
    institution_id bigint NOT NULL REFERENCES institution(id),
    is_active      boolean NOT NULL DEFAULT true,
    CONSTRAINT membership_user_institution_key UNIQUE (user_id, institution_id)
);
CREATE TABLE IF NOT EXISTS membership_roles (
    membership_id bigint NOT NULL REFERENCES membership(id),
    role          varchar(255) NOT NULL
        CONSTRAINT membership_roles_role_check CHECK (role IN ('STUDENT', 'FACILITATOR', 'ADMIN', 'SUPER_ADMIN')),
    PRIMARY KEY (membership_id, role)
);

-- One membership per existing (user, institution). The old account-wide
-- "deactivated" flag was set by institution admins, so it becomes the
-- membership's; the account itself stays enabled.
INSERT INTO membership (created_at, public_id, user_id, institution_id, is_active)
SELECT u.created_at, gen_random_uuid(), u.id, u.institution_id, u.is_active
FROM app_user u
WHERE u.institution_id IS NOT NULL
  AND NOT u.is_deleted
  AND NOT EXISTS (SELECT 1 FROM membership m WHERE m.user_id = u.id AND m.institution_id = u.institution_id);

INSERT INTO membership_roles (membership_id, role)
SELECT m.id, ur.role
FROM membership m
JOIN app_user u ON u.id = m.user_id AND u.institution_id = m.institution_id
JOIN user_roles ur ON ur.user_id = u.id
ON CONFLICT DO NOTHING;

UPDATE app_user u SET is_active = true
WHERE EXISTS (SELECT 1 FROM membership m WHERE m.user_id = u.id);

UPDATE app_user u SET last_active_institution_id = u.institution_id
WHERE u.last_active_institution_id IS NULL AND u.institution_id IS NOT NULL;

-- ── Sessions: tag existing refresh tokens with their institution ─────────
ALTER TABLE refresh_token ADD COLUMN IF NOT EXISTS institution_id bigint REFERENCES institution(id);
UPDATE refresh_token r SET institution_id = u.institution_id
FROM app_user u WHERE u.id = r.user_id AND r.institution_id IS NULL;

-- ── Invites: describe the invitee (account created on acceptance) ────────
ALTER TABLE staff_invite_token ADD COLUMN IF NOT EXISTS institution_id bigint REFERENCES institution(id);
ALTER TABLE staff_invite_token ADD COLUMN IF NOT EXISTS email varchar(255);
ALTER TABLE staff_invite_token ADD COLUMN IF NOT EXISTS role varchar(255);
ALTER TABLE staff_invite_token ADD COLUMN IF NOT EXISTS first_name varchar(255);
ALTER TABLE staff_invite_token ADD COLUMN IF NOT EXISTS middle_name varchar(255);
ALTER TABLE staff_invite_token ADD COLUMN IF NOT EXISTS last_name varchar(255);
ALTER TABLE staff_invite_token ADD COLUMN IF NOT EXISTS phone_number varchar(255);
ALTER TABLE staff_invite_token ADD COLUMN IF NOT EXISTS invited_by_id bigint REFERENCES app_user(id);

UPDATE staff_invite_token t SET
    institution_id = u.institution_id,
    email          = lower(u.email),
    role           = COALESCE((SELECT ur.role FROM user_roles ur WHERE ur.user_id = u.id
                                ORDER BY CASE ur.role WHEN 'SUPER_ADMIN' THEN 0 WHEN 'ADMIN' THEN 1
                                                      WHEN 'FACILITATOR' THEN 2 ELSE 3 END LIMIT 1), 'FACILITATOR'),
    first_name     = u.first_name,
    middle_name    = u.middle_name,
    last_name      = u.last_name,
    phone_number   = u.phone_number
FROM app_user u
WHERE u.id = t.user_id AND t.institution_id IS NULL;

ALTER TABLE staff_invite_token ALTER COLUMN institution_id SET NOT NULL;
ALTER TABLE staff_invite_token ALTER COLUMN email SET NOT NULL;
ALTER TABLE staff_invite_token ALTER COLUMN role SET NOT NULL;
ALTER TABLE staff_invite_token ALTER COLUMN user_id DROP NOT NULL; -- set only on these legacy invites
ALTER TABLE staff_invite_token DROP CONSTRAINT IF EXISTS staff_invite_token_role_check;
ALTER TABLE staff_invite_token ADD CONSTRAINT staff_invite_token_role_check
    CHECK (role IN ('STUDENT', 'FACILITATOR', 'ADMIN', 'SUPER_ADMIN'));

-- ── Audit actions ────────────────────────────────────────────────────────
ALTER TABLE audit_log DROP CONSTRAINT IF EXISTS audit_log_action_check;
ALTER TABLE audit_log ADD CONSTRAINT audit_log_action_check CHECK (action IN (
    'CREATE', 'UPDATE', 'DELETE', 'APPROVE', 'DENY', 'OVERRIDE', 'EXPORT',
    'LOGIN', 'LOGIN_FAILED', 'LOGOUT', 'CONSENT_GIVEN', 'CONSENT_REVOKED', 'ACCOUNT_LOCKED',
    'INSTITUTION_CREATED', 'PLATFORM_ACCESS'));

COMMIT;
